# viewport 200 x 150. Slightly wobbly, not closed perfectly: like one pen stroke.
def wobbly(pts, bow=1.6, seed=3):
    """Straight-ish pen strokes between points; each segment bows a little, alternating sides."""
    out = [f"M{pts[0][0]},{pts[0][1]}"]
    for i in range(1, len(pts)):
        (x0, y0), (x1, y1) = pts[i-1], pts[i]
        dx, dy = x1 - x0, y1 - y0; n = (dx*dx + dy*dy) ** 0.5 or 1
        nx, ny = -dy / n, dx / n; k = bow * (1 if (i + seed) % 2 else -1)
        c1 = (round(x0 + dx/3 + nx*k, 1), round(y0 + dy/3 + ny*k, 1))
        c2 = (round(x0 + 2*dx/3 + nx*k*0.6, 1), round(y0 + 2*dy/3 + ny*k*0.6, 1))
        out.append(f"C{c1[0]},{c1[1]} {c2[0]},{c2[1]} {x1},{y1}")
    return " ".join(out)

