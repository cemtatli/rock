import math, random

def _smooth(pts, closed=False):
    """Catmull-Rom through points -> cubic path string."""
    P = pts + pts[:3] if closed else [pts[0]] + pts + [pts[-1]]
    out = [f"M{P[1][0]:.1f},{P[1][1]:.1f}"] if closed else [f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"]
    rng = range(1, len(pts) + 1) if closed else range(1, len(P) - 2)
    for i in rng:
        p0, p1, p2, p3 = P[i-1], P[i], P[i+1], P[i+2]
        c1 = (p1[0] + (p2[0]-p0[0])/6, p1[1] + (p2[1]-p0[1])/6)
        c2 = (p2[0] - (p3[0]-p1[0])/6, p2[1] - (p3[1]-p1[1])/6)
        out.append(f"C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}")
    return " ".join(out)

def lumpy_circle(cx, cy, r, n, jit, seed, overshoot=0.35):
    rnd = random.Random(seed); a0 = rnd.uniform(0, 6.28)
    steps = int(n * (1 + overshoot))
    pts = []
    for k in range(steps + 1):
        a = a0 + 2*math.pi*k/n
        rr = r + rnd.uniform(-jit, jit)
        pts.append((cx + rr*math.cos(a), cy + rr*math.sin(a)))
    return _smooth(pts)

def shaky(points, jit, seed):
    rnd = random.Random(seed)
    return _smooth([(x + rnd.uniform(-jit, jit), y + rnd.uniform(-jit, jit)) for x, y in points])

def wedge(start, end, w, seed):
    """Cuneiform wedge: a nail-head at start tapering to a point at end."""
    rnd = random.Random(seed)
    dx, dy = end[0]-start[0], end[1]-start[1]; L = math.hypot(dx, dy); ux, uy = dx/L, dy/L; nx, ny = -uy, ux
    head = (start[0] - ux*w*0.55, start[1] - uy*w*0.55)
    a = (start[0] + nx*w/2, start[1] + ny*w/2); b = (start[0] - nx*w/2, start[1] - ny*w/2)
    j = lambda p: (p[0] + rnd.uniform(-0.4, 0.4), p[1] + rnd.uniform(-0.4, 0.4))
    a, b, head = j(a), j(b), j(head)
    tip = end
    return (f"M{head[0]:.1f},{head[1]:.1f} L{a[0]:.1f},{a[1]:.1f} "
            f"Q{(a[0]+tip[0])/2 + nx*0.6:.1f},{(a[1]+tip[1])/2 + ny*0.6:.1f} {tip[0]:.1f},{tip[1]:.1f} "
            f"Q{(b[0]+tip[0])/2 - nx*0.3:.1f},{(b[1]+tip[1])/2 - ny*0.3:.1f} {b[0]:.1f},{b[1]:.1f} Z")

def nail(head, tip, hw, sw, seed, depth=1.0):
    """Cuneiform wedge: a flat back edge at [head], a triangular head narrowing to a neck,
    then a thin tail out to [tip]. hw = head width, sw = neck width, depth = head length / hw."""
    rnd = random.Random(seed)
    dx, dy = tip[0]-head[0], tip[1]-head[1]; L = math.hypot(dx, dy); ux, uy = dx/L, dy/L; nx, ny = -uy, ux
    j = lambda p, a=0.3: (p[0] + rnd.uniform(-a, a), p[1] + rnd.uniform(-a, a))
    b1 = j((head[0] + nx*hw/2, head[1] + ny*hw/2)); b2 = j((head[0] - nx*hw/2, head[1] - ny*hw/2))
    nk = hw * depth
    n1 = j((head[0] + ux*nk + nx*sw/2, head[1] + uy*nk + ny*sw/2), 0.15)
    n2 = j((head[0] + ux*nk - nx*sw/2, head[1] + uy*nk - ny*sw/2), 0.15)
    f = lambda p: f"{p[0]:.1f},{p[1]:.1f}"
    return f"M{f(b1)} L{f(n1)} L{f(tip)} L{f(n2)} L{f(b2)} Z"

