def icon_xml(items, stroke=4.2):
    rows = []
    for item in items:
        kind, d = item[0], item[1]
        w = item[2] if len(item) > 2 else stroke
        if kind == "s":
            rows.append(f'    <path android:pathData="{d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{w}" '
                        f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />')
        else:
            rows.append(f'    <path android:pathData="{d}" android:fillColor="#FFFFFFFF" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by design/doodle.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="48dp" android:height="48dp" android:viewportWidth="48" android:viewportHeight="48">\n'
            + "\n".join(rows) + "\n</vector>\n")

def icon_preview(path, scale=6):
    from PIL import ImageDraw
    im = Image.new("RGB", (48*scale*len(ICONS), 48*scale), (230,229,226)); dr = ImageDraw.Draw(im)
    for n, (name, items) in enumerate(ICONS.items()):
        ox = n*48*scale
        for item in items:
            kind, d = item[0], item[1]
            pts = [(ox + x*scale, y*scale) for x, y in polyline(d.replace("Q", "C").replace(" Z", ""), 12)] if kind == "s" else None
            if kind == "s":
                dr.line(pts, fill=(14,14,13), width=int(4.2*scale), joint="curve")
            else:
                nums = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", d)]
                poly = [(ox + nums[i]*scale, nums[i+1]*scale) for i in range(0, len(nums)-1, 2)]
                dr.polygon(poly, fill=(14,14,13))
    im.save(path)

