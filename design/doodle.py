def tokens(d):
    return re.findall(r"[MCL]|-?\d+(?:\.\d+)?", d)

def polyline(d, steps=24):
    t = tokens(d); i = 0; pts = []; cur = None; cmd = None
    while i < len(t):
        if t[i] in "MCL": cmd = t[i]; i += 1
        if cmd == "M":
            cur = (float(t[i]), float(t[i+1])); i += 2; pts.append(cur); cmd = "L"
        elif cmd == "L":
            cur = (float(t[i]), float(t[i+1])); i += 2; pts.append(cur)
        elif cmd == "C":
            p1 = (float(t[i]), float(t[i+1])); p2 = (float(t[i+2]), float(t[i+3])); p3 = (float(t[i+4]), float(t[i+5])); i += 6
            p0 = cur
            for k in range(1, steps + 1):
                u = k / steps; a = (1-u)**3; b = 3*(1-u)**2*u; c = 3*(1-u)*u*u; e = u**3
                pts.append((a*p0[0]+b*p1[0]+c*p2[0]+e*p3[0], a*p0[1]+b*p1[1]+c*p2[1]+e*p3[1]))
            cur = p3
    return pts

def preview(path, scale=4, fg=(14,14,13), bg=(230,229,226), w=3.4):
    im = Image.new("RGB", (200*scale, 150*scale), bg); dr = ImageDraw.Draw(im)
    for d in ROCK:
        pts = [(x*scale, y*scale) for x, y in polyline(d)]
        dr.line(pts, fill=fg, width=int(w*scale), joint="curve")
        r = w*scale/2
        for p in (pts[0], pts[-1]): dr.ellipse((p[0]-r, p[1]-r, p[0]+r, p[1]+r), fill=fg)
    im.save(path)

def vector(color, width, vw, vh, tx=0, ty=0, s=1.0):
    paths = "\n".join(
        f'        <path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{width}" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />'
        for d in ROCK)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by design/doodle.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{vw}dp" android:height="{vh}dp" android:viewportWidth="{vw}" android:viewportHeight="{vh}">
    <group android:translateX="{tx}" android:translateY="{ty}" android:scaleX="{s}" android:scaleY="{s}">
{paths}
    </group>
</vector>
'''

