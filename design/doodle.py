def sun():
    items = [("s", lumpy_circle(24, 24, 8.5, 7, 0.7, 31, overshoot=0.2))]
    rnd = random.Random(32)
    for k in range(8):
        a = k * math.pi / 4 + rnd.uniform(-0.12, 0.12)
        r0, r1 = 13.5 + rnd.uniform(-0.6, 0.6), 19.5 + rnd.uniform(-1.2, 1.2)
        items.append(("s", shaky([(24 + r0*math.cos(a), 24 + r0*math.sin(a)), (24 + r1*math.cos(a), 24 + r1*math.sin(a))], 0.3, 40 + k)))
    return items

def fire(seed, lean):
    """One frame of a campfire: two crossed logs, an outer flame with three tongues, a small inner flame."""
    rnd = random.Random(seed)
    h = lambda base: base + rnd.uniform(-5, 5)
    outer = [(40, 112), (30, 96), (32, 78), (40 + lean, h(52)), (46, 74), (52 + lean, h(22)), (60, 62),
             (66 + lean, h(44)), (72, 70), (76, 92), (68, 112)]
    inner = [(48, 112), (45, 100), (50 + lean*0.6, h(78)), (55, 92), (58 + lean*0.6, h(84)), (62, 102), (58, 112)]
    return [
        ("s", shaky(outer, 1.0, seed)),
        ("s", shaky(inner, 0.8, seed + 1)),
        ("s", shaky([(18, 126), (60, 112), (102, 98)], 0.8, 51)),
        ("s", shaky([(20, 100), (62, 114), (100, 127)], 0.8, 52)),
    ]

def hand_stencil(path):
    """Negative hand print: ochre-less spray of dots around a bare hand, like the cave walls.
    viewport 120 x 140, filled dots only."""
    fingers = [((44, 70), (30, 30), 11), ((54, 64), (50, 18), 11), ((64, 64), (68, 20), 11),
               ((72, 70), (85, 34), 10), ((40, 92), (16, 74), 11)]
    palm_c, palm_rx, palm_ry = (60, 92), 22, 25
    def inside(x, y, pad=0):
        if ((x - palm_c[0]) / (palm_rx + pad)) ** 2 + ((y - palm_c[1]) / (palm_ry + pad)) ** 2 <= 1: return True
        if 50 <= x <= 70 and 100 <= y <= 132 + pad: return True  # wrist
        for (a, b, w) in fingers:
            ax, ay = a; bx, by = b; dx, dy = bx - ax, by - ay
            t = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
            if math.hypot(x - (ax + t * dx), y - (ay + t * dy)) <= w / 2 + pad: return True
        return False
    rnd = random.Random(77); dots = []
    while len(dots) < 900:
        x, y = rnd.uniform(0, 120), rnd.uniform(0, 140)
        if inside(x, y): continue
        # density falls off away from the hand edge
        near = 0
        for pad in (3, 7, 12, 18):
            if inside(x, y, pad): near = pad; break
        if near == 0: continue
        if rnd.random() > {3: 1.0, 7: 0.75, 12: 0.35, 18: 0.12}[near]: continue
        r = rnd.uniform(0.6, 1.5)
        # circle as four cubics: arc commands ("a") crash Compose's vector path parser
        k = 0.5523 * r
        dots.append(f"M{x+r:.1f},{y:.1f} C{x+r:.1f},{y+k:.1f} {x+k:.1f},{y+r:.1f} {x:.1f},{y+r:.1f} "
                    f"C{x-k:.1f},{y+r:.1f} {x-r:.1f},{y+k:.1f} {x-r:.1f},{y:.1f} "
                    f"C{x-r:.1f},{y-k:.1f} {x-k:.1f},{y-r:.1f} {x:.1f},{y-r:.1f} "
                    f"C{x+k:.1f},{y-r:.1f} {x+r:.1f},{y-k:.1f} {x+r:.1f},{y:.1f} Z")
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by design/doodle.py -->\n'
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           '    android:width="120dp" android:height="140dp" android:viewportWidth="120" android:viewportHeight="140">\n'
           # many short paths: one huge pathData string gets mangled by aapt2 (Compose then fails to parse it)
           + "".join(f'    <path android:fillColor="#FFFFFFFF" android:pathData="{" ".join(dots[i:i+40])}" />\n' for i in range(0, len(dots), 40))
           + '</vector>\n')
    open(path, "w").write(xml)

